export function applyPaletteCss(palette) {
  const root = document.documentElement;
  root.style.setProperty("--accent", palette.css.accent);
  root.style.setProperty("--accent-2", palette.css.accent2);
  root.style.setProperty("--accent-3", palette.css.accent3);
  document.querySelector('meta[name="theme-color"]')?.setAttribute("content", "#0a0112");
}
